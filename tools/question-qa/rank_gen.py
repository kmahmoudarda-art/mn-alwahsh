ORD=["أكبر","ثاني أكبر","ثالث أكبر","رابع أكبر","خامس أكبر","سادس أكبر","سابع أكبر","ثامن أكبر"]
def ranked(title_fmt,items,maxn=6):
    """items ordered best->worse. title_fmt like 'ما {ord} {what}؟' with {ord} replaced by ordinal phrase."""
    out=[]
    for i,it in enumerate(items[:maxn]):
        w=[x for x in items if x!=it]; r=random.Random(hash(title_fmt+it)%10**6); r.shuffle(w)
        out.append((title_fmt.replace('{ord}',ORD[i]),[it]+w[:3]))
    return out
