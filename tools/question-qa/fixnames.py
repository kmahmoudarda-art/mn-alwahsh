def kind(q):
    if re.search(r'ملحن|الملحن',q): return 'COMP'
    if re.search(r'كاتب كلمات|الشاعر',q): return 'POET'
    if re.search(r'مخرج',q): return 'DIR'
    if re.search(r'كاتب',q): return 'WRI'
    if re.search(r'الممثلة|الفنانة|بطلة|المطرب',q): return 'ACTR'
    if re.search(r'بطل|الممثل|النجم',q): return 'ACT'
    return None
def fix(q,o):
    k=kind(q)
    if not k: return o
    wc=lambda s:len(s.split()); n=len(o[0].split()); o=list(o)
    rnd=random.Random(hash(q)%10**6)
    cand=[c for c in POOLS[k].get(n,[]) if c not in o]; rnd.shuffle(cand)
    for j in range(1,4):
        if wc(o[j])!=n and cand:
            o[j]=cand.pop()
    return o
